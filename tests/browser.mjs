import puppeteer from 'puppeteer-core';
import path from 'node:path';
const file = 'file://' + path.resolve('dist/chess-trivia-rpg-3d.html');
const out = process.argv[2] || '/tmp/sim/shots';
import fs from 'node:fs'; fs.mkdirSync(out,{recursive:true});
const browser = await puppeteer.launch({ executablePath:'/usr/bin/google-chrome', headless:'new', args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--window-size=1280,800'], defaultViewport:{width:1280,height:800} });
const page = await browser.newPage();
const errs=[]; const reqs=[];
page.on('console',m=>{ if(['error','warning'].includes(m.type())) errs.push(m.type()+': '+m.text()); });
page.on('pageerror',e=>errs.push('PAGEERROR '+e.message));
page.on('request',r=>{ if(!r.url().startsWith('file:')&&!r.url().startsWith('data:')) reqs.push(r.url()); });
await page.goto(file); await new Promise(r=>setTimeout(r,2500));
await page.screenshot({path:out+'/01_intro.png'});
await page.click('#introGo'); await new Promise(r=>setTimeout(r,1500));
await page.screenshot({path:out+'/02_board.png'});
const info = await page.evaluate(()=>({children: __view.scene.children.length, pieces: __view.pieces.size, turn: __G.st.turn, moves: __G.moves.length}));
console.log('init',JSON.stringify(info));
console.log('errors so far',JSON.stringify(errs));
console.log('external reqs',JSON.stringify(reqs));
await browser.close();
